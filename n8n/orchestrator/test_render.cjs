const fs=require('fs'),assert=require('assert');
const template=JSON.parse(fs.readFileSync(__dirname+'/pptx_template.json','utf8'));
const logic=fs.readFileSync(__dirname+'/briefing.js','utf8')+'\n'+fs.readFileSync(__dirname+'/pptx.js','utf8');
const {makeBriefing,buildPowerPoint}=new Function('TEMPLATE',logic+'\nreturn {makeBriefing,buildPowerPoint};')(template);
const research=JSON.parse(fs.readFileSync(process.argv[2],'utf8'));
assert.throws(()=>makeBriefing({approved:false},research,[],'blocked','2026-10-24T20:00:00Z'),/approved/);
const briefing=makeBriefing(null,research,[],'archived-preview-test','2026-10-24T20:00:00Z','preview');
const before=JSON.stringify(briefing);
const old={company_key:briefing.company_key,record_type:'research_preview',run_time:briefing.run_time,payload_json:before};
const second=makeBriefing(null,research,[old],'second-preview-test','2026-10-24T21:00:00Z','preview');
assert.equal(second.memory.previous_run_id,briefing.run_id);
assert.equal(second.memory.newly_observed_sources.length,0);
assert.equal(second.memory.new_signals.length,0);
assert.equal(JSON.stringify(briefing),before);
const result=buildPowerPoint(briefing);
assert(result.buffer.readUInt32LE(0)===0x04034b50);assert(result.slide_count>=3);assert(result.pages.every(p=>p.visual));
assert(result.pages.some(p=>p.title==='Sources and publication dates'));
assert(!briefing.signals.some(s=>s.company==='Example Foods'));
fs.writeFileSync(process.argv[3],result.buffer);
fs.writeFileSync(process.argv[3].replace(/\.pptx$/,'.json'),JSON.stringify(briefing,null,2)+'\n');
console.log(JSON.stringify({passed:true,slides:result.slide_count,bytes:result.buffer.length,retained_sources:briefing.sources.length,memory_comparison:'passed',unapproved_research:'blocked',synthetic_findings_excluded:true}));
